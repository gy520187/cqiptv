def get_fanmingming_name(channel_name: str) -> str:
    import re
    from .utils import normalize_channel_name
    norm = normalize_channel_name(channel_name)
    if norm in FANMINGMING_ALIAS:
        return FANMINGMING_ALIAS[norm]
    norm_clean = re.sub(r"[\s\-_·＋]", "", norm)
    for k, v in FANMINGMING_ALIAS.items():
        if re.sub(r"[\s\-_·＋]", "", k) == norm_clean:
            return v
    return norm